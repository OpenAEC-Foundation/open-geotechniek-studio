"""Build the symbol font that the PDF reports embed for Greek letters and maths.

The reports set ordinary text in the standard PDF sans (not embedded). That
font has no Greek letters and no mathematical operators, so those characters
come from a small subset of Inter, the typeface of the app itself (SIL Open
Font License 1.1, see src/styles/blueprint/fonts/Inter-OFL.txt; the licence
allows embedding and subsetting and Inter declares no reserved font name).

Run from apps/desktop:  python scripts/build-report-symbol-font.py
Requires fontTools. Writes src/report/reportSymbolFont.ts.
"""
import base64
import io
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "src" / "styles" / "blueprint" / "fonts"
OUT = ROOT / "src" / "report" / "reportSymbolFont.ts"

WANTED = (
    list(range(0x0391, 0x03A2)) + list(range(0x03A3, 0x03AA))  # Greek capitals
    + list(range(0x03B1, 0x03CA)) + [0x03D1, 0x03D5]            # Greek small letters
    + [0x2212, 0x2264, 0x2265, 0x2260, 0x2248, 0x221A, 0x2211, 0x2206, 0x221E, 0x2202, 0x222B]
    + [0x2190, 0x2192, 0x2194, 0x21D2, 0x2032, 0x2033, 0x2205, 0x2219, 0x22C5]
    + [0x2070] + list(range(0x2074, 0x207C))                    # superscripts
    + list(range(0x2080, 0x208A))                               # subscripts
    + [0x2300, 0x25A1]                                          # diameter, square
)


def build(weight: str) -> tuple[str, list[int]]:
    font = TTFont(FONTS / f"Inter-{weight}.ttf")
    have = sorted(cp for cp in WANTED if cp in font.getBestCmap())
    options = subset.Options()
    options.layout_features = []
    options.hinting = False
    options.notdef_outline = True
    options.name_IDs = [1, 2, 3, 4, 6]
    options.drop_tables += ["GSUB", "GPOS", "GDEF", "STAT", "meta", "DSIG"]
    sub = subset.Subsetter(options)
    sub.populate(unicodes=have)
    sub.subset(font)
    buf = io.BytesIO()
    font.save(buf)
    return base64.b64encode(buf.getvalue()).decode("ascii"), have


def main() -> None:
    regular, have = build("Regular")
    bold, have_bold = build("SemiBold")
    assert have == have_bold, "the two weights must cover the same characters"
    chars = "".join(f"\\u{cp:04x}" for cp in have)
    OUT.write_text(
        "// Generated by scripts/build-report-symbol-font.py; do not edit by hand.\n"
        "// Subset of Inter (SIL Open Font License 1.1, src/styles/blueprint/fonts/Inter-OFL.txt)\n"
        "// with only Greek letters and mathematical signs, for the PDF reports.\n"
        f'export const SYMBOL_CHARS = "{chars}";\n'
        f'export const SYMBOL_REGULAR_TTF = "{regular}";\n'
        f'export const SYMBOL_BOLD_TTF = "{bold}";\n',
        encoding="utf-8",
        newline="\n",
    )
    print(f"{len(have)} characters; regular {len(regular)} and bold {len(bold)} base64 characters")
    missing = [f"U+{cp:04X}" for cp in WANTED if cp not in have]
    if missing:
        print("not in the font:", " ".join(missing))


if __name__ == "__main__":
    main()
