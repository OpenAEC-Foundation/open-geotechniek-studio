import type { Cpt, ProjectMeta } from "../types/cpt";

// Matches cpt-core/src/ifc.rs: exchange previews, not schema-validated IFC models.
export const IFC_EXPORT_NOTE = "Experimentele IFC-uitwisseling; nog niet gevalideerd tegen het officiële IFC-schema.";
const nativeNote = "Generated by Open Geotechniek Studio — placeholder structure (not schema-valid IFC4x3)";
type Format = "ifc4x3" | "ifcx";

function guid(kind: string, key: string): string {
  let hash = BigInt("0xcbf29ce484222325");
  for (const byte of new TextEncoder().encode(`${kind}|${key}`)) {
    hash = BigInt.asUintN(64, (hash ^ BigInt(byte)) * BigInt("0x100000001b3"));
  }
  const rotated = BigInt.asUintN(32, (hash << BigInt(13)) | (hash >> BigInt(51)));
  return `OGS${hash.toString(16).padStart(16, "0")}${rotated.toString(16).padStart(8, "0")}`;
}

function step(value: string): string {
  return value.replace(/[\u0000-\u001f]/g, "").replace(/\\/g, "\\\\").replace(/'/g, "''");
}

export function generateIfcContent(cpts: Cpt[], project: ProjectMeta, format: Format): string {
  const timestamp = new Date().toISOString();
  if (format === "ifcx") {
    return JSON.stringify({
      schema: "ifcx-cpt-0.1",
      header: { originating_system: "Open Geotechniek Studio", timestamp, note: nativeNote },
      objects: [
        { type: "IfcProject", id: guid("project", project.title), name: project.title,
          client: project.client, location: project.location, project_number: project.project_number,
          author: project.author, date: project.date },
        { type: "IfcSite", id: guid("site", project.location), name: `Site - ${project.location}` },
        ...cpts.map(cpt => ({
          type: "OpenGeoCpt", id: cpt.id, guid: guid("cpt", cpt.id),
          source_file: cpt.metadata.source_file, project_name: cpt.metadata.project_name ?? null,
          project_number: cpt.metadata.project_number ?? null, date: cpt.metadata.date ?? null,
          ground_level_nap: cpt.metadata.ground_level_nap ?? null,
          position: cpt.position ? { ...cpt.position, z_nap: cpt.position.z_nap ?? null } : null,
          points: cpt.points.map(p => ({ depth: p.depth, depth_nap: p.depth_nap ?? null,
            qc: p.qc ?? null, fs: p.fs ?? null, rf: p.rf ?? null, u2: p.u2 ?? null, inclination: p.inclination ?? null })),
        })),
      ],
    }, null, 2);
  }
  const safeName = project.title.replace(/[^A-Za-z0-9_-]/g, "_");
  const lines = [
    "ISO-10303-21;", `/* ${nativeNote} */`, "HEADER;",
    "FILE_DESCRIPTION(('Open Geotechniek Studio CPT export'),'2;1');",
    `FILE_NAME('${safeName}.ifc','${timestamp.slice(0, 19)}',('${step(project.author)}'),('${step(project.client)}'),'Open Geotechniek Studio','cpt-core ifc writer','');`,
    "FILE_SCHEMA(('IFC4X3'));", "ENDSEC;", "DATA;",
    `#1 = IFCPROJECT('${guid("project", project.title)}',$,'${step(project.title)}','${step(`${project.client} - ${project.location} (${project.project_number})`)}',$,$,$,(#10),#5);`,
    "#5 = IFCUNITASSIGNMENT((#6,#7));", "#6 = IFCSIUNIT(*,.LENGTHUNIT.,$,.METRE.);",
    "#7 = IFCSIUNIT(*,.PRESSUREUNIT.,.MEGA.,.PASCAL.);",
    "#10 = IFCGEOMETRICREPRESENTATIONCONTEXT($,'Model',3,1.0E-5,#11,$);",
    "#11 = IFCAXIS2PLACEMENT3D(#12,$,$);", "#12 = IFCCARTESIANPOINT((0.,0.,0.));",
    `#20 = IFCSITE('${guid("site", project.location)}',$,'${step(`Site - ${project.location}`)}',$,$,$,$,$,$,$,$,$,$,$);`,
  ];
  cpts.forEach((cpt, index) => {
    const id = 100 + index * 10;
    const x = cpt.position?.x_rd ?? 0, y = cpt.position?.y_rd ?? 0, z = cpt.position?.z_nap ?? 0;
    const maxDepth = cpt.points.reduce((max, p) => Math.max(max, p.depth), 0);
    const list = (key: "depth" | "qc" | "fs" | "rf", type: string, digits: number) =>
      cpt.points.map(p => p[key] == null ? "$" : `${type}(${p[key]!.toFixed(digits)})`).join(",");
    lines.push(
      `#${id + 3} = IFCCARTESIANPOINT((${x.toFixed(3)},${y.toFixed(3)},${z.toFixed(3)}));`,
      `#${id + 2} = IFCAXIS2PLACEMENT3D(#${id + 3},$,$);`,
      `#${id + 1} = IFCLOCALPLACEMENT($,#${id + 2});`,
      `#${id} = IFCBUILDINGELEMENTPROXY('${guid("cpt", cpt.id)}',$,'${step(cpt.id)}','CPT - ${cpt.points.length} points, depth ${maxDepth.toFixed(2)} m',$,#${id + 1},$,$,$);`,
      `#${id + 5} = IFCPROPERTYLISTVALUE('Depth',$,(${list("depth", "IFCLENGTHMEASURE", 3)}),IFCLENGTHMEASURE);`,
      `#${id + 6} = IFCPROPERTYLISTVALUE('Qc',$,(${list("qc", "IFCPRESSUREMEASURE", 4)}),IFCPRESSUREMEASURE);`,
      `#${id + 7} = IFCPROPERTYLISTVALUE('Fs',$,(${list("fs", "IFCPRESSUREMEASURE", 4)}),IFCPRESSUREMEASURE);`,
      `#${id + 8} = IFCPROPERTYLISTVALUE('Rf',$,(${list("rf", "IFCREAL", 4)}),IFCREAL);`,
      `#${id + 4} = IFCPROPERTYSET('${guid("pset", cpt.id)}',$,'OpenGeo_CptMeasurements',$,(#${id + 5},#${id + 6},#${id + 7},#${id + 8}));`,
      `#${id + 9} = IFCRELDEFINESBYPROPERTIES('${guid("rel", cpt.id)}',$,$,$,(#${id}),#${id + 4});`,
    );
  });
  lines.push("ENDSEC;", "END-ISO-10303-21;");
  return lines.join("\n") + "\n";
}
